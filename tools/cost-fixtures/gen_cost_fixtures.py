#!/usr/bin/env python3
"""Generates Tests/CELTests/Fixtures/RuntimeCostFixtures.swift from cel-go via tools/oracle.

For every expression below, records cel-go's result and actual runtime cost (cel.CostTracking) in checked
and parse-only mode, so the interpreter's runtime cost port (interpreter/runtimecost.go) is pinned to
cel-go's numbers.

Usage (from the repository root):
  (cd tools/oracle && go build -o /tmp/cel-oracle .)
  python3 tools/cost-fixtures/gen_cost_fixtures.py /tmp/cel-oracle > Tests/CELTests/Fixtures/RuntimeCostFixtures.swift
"""
