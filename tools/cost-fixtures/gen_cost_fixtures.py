def run(oracle, exprs, check):
    reqs = "".join(
        json.dumps({"id": str(i), "kind": "eval", "check": check, "expr": e,
                    "config": {"extensions": [{"name": "optional"}]}}) + "\n"
        for i, e in enumerate(exprs))
    out = subprocess.run([oracle], input=reqs, capture_output=True, text=True, check=True).stdout
    results = {}
    for line in out.splitlines():
        d = json.loads(line)
        results[int(d["id"])] = d
    return results


def swift_string(s):
    return json.dumps(s)


def main():
    oracle = sys.argv[1]
    checked = run(oracle, EXPRS, True)
    unchecked = run(oracle, EXPRS, False)
    print("// Generated by tools/cost-fixtures/gen_cost_fixtures.py from cel-go v0.32.0 via tools/oracle.")
    print("// Do not edit by hand.")
    print()
    print("/// (expression, checked cost, parse-only cost, cel-go result is an error)")
    print("let runtimeCostFixtures: [(String, UInt64, UInt64, Bool)] = [")
    for i, e in enumerate(EXPRS):
        c, u = checked[i], unchecked[i]
        if "oracle_error" in c or "error" in c or "oracle_error" in u or "error" in u:
            sys.stderr.write(f"skipping {e}: {c} {u}\n")
            continue
        is_err = "error" in c["result"]
        print(f"  ({swift_string(e)}, {c['cost']}, {u['cost']}, {'true' if is_err else 'false'}),")
    print("]")


if __name__ == "__main__":
    main()
