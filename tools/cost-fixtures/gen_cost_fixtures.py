    "2 in [1, 2, 3]", "'a' in {'a': 1}", "size('123')", "'123'.size()", "size([1, 2])",
    "'12345678901234567890' == '123456789012345678901234567890'",
    "'abc' < 'abd'", "b'abc' < b'abd'", "'hello' + ' world'", "b'hello' + b' world'",
    "'hello world'.contains('o w')", "'hello world'.startsWith('hello')", "'hello world'.endsWith('world')",
